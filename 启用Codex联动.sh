#!/bin/bash
set -euo pipefail
ROOT="$(cd "$(dirname "$0")" && pwd)"
PET_INSTALL="$HOME/Library/Application Support/PaiXiaoXing"
PET_LABEL="local.paixiaoxing.codex-launch"
PET_AGENT="$HOME/Library/LaunchAgents/$PET_LABEL.plist"
PET_LOG="$HOME/Library/Logs/PaiXiaoXing"
PET_UID="$(id -u)"
test -x "$ROOT/派小星.app/Contents/MacOS/PaiXiaoXing"
test -x "$ROOT/联动组件/CodexAutoStart"
test -f "$ROOT/联动组件/LaunchAgent.plist"
mkdir -p "$PET_INSTALL" "$HOME/Library/LaunchAgents" "$PET_LOG"
/bin/launchctl bootout "gui/$PET_UID/$PET_LABEL" >/dev/null 2>&1 || true
/usr/bin/ditto "$ROOT/派小星.app" "$PET_INSTALL/派小星.app"
/bin/cp "$ROOT/联动组件/CodexAutoStart" "$PET_INSTALL/CodexAutoStart"
/bin/chmod 755 "$PET_INSTALL/CodexAutoStart"
/bin/cp "$ROOT/联动组件/LaunchAgent.plist" "$PET_AGENT"
/usr/bin/plutil -insert Label -string "$PET_LABEL" "$PET_AGENT"
/usr/bin/plutil -insert ProgramArguments -array "$PET_AGENT"
/usr/bin/plutil -insert ProgramArguments.0 -string "$PET_INSTALL/CodexAutoStart" "$PET_AGENT"
/usr/bin/plutil -insert ProgramArguments.1 -string "--pet-app" "$PET_AGENT"
/usr/bin/plutil -insert ProgramArguments.2 -string "$PET_INSTALL/派小星.app" "$PET_AGENT"
/usr/bin/plutil -insert RunAtLoad -bool true "$PET_AGENT"
/usr/bin/plutil -insert KeepAlive -bool true "$PET_AGENT"
/usr/bin/plutil -insert ProcessType -string Background "$PET_AGENT"
/usr/bin/plutil -insert LimitLoadToSessionType -string Aqua "$PET_AGENT"
/usr/bin/plutil -insert ThrottleInterval -integer 10 "$PET_AGENT"
/usr/bin/plutil -insert StandardOutPath -string "$PET_LOG/codex-start.log" "$PET_AGENT"
/usr/bin/plutil -insert StandardErrorPath -string "$PET_LOG/codex-start-error.log" "$PET_AGENT"
/bin/chmod 600 "$PET_AGENT"
/bin/launchctl enable "gui/$PET_UID/$PET_LABEL"
/bin/launchctl bootstrap "gui/$PET_UID" "$PET_AGENT"
printf '已启用：下次启动 Codex 时自动打开派小星。\n程序固定位置：%s\n' "$PET_INSTALL"
